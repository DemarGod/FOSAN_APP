-- 46 · ORDEN DEL SQL · Paquete 25: "foto" de la base actual. SOLO LECTURA: no cambia nada.
--   Entrega, en una sola tabla, la definición real de todo lo que existe hoy en la base:
--   extensiones, tipos, tablas, restricciones, índices, funciones, vistas, triggers, seguridad (RLS), permisos y buckets.
--   Con esto se arma la carpeta supabase/esquema/ del repositorio.
-- Uso: seleccionar TODO y Run. Luego en el resultado: Export → Download CSV
--      y guardar el archivo como foto_base.csv
--      Si Supabase avisa "creates a table without enabling RLS": elegir Run without RLS (es falsa alarma, no crea nada).
--      Después: python supabase/herramientas/armar_esquema.py foto_base.csv supabase/esquema

with
tablas as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('r', 'p')
),
foto as (
  -- 1 · Extensiones
  select 1 as orden, 'extension' as tipo, e.extname::text as nombre,
         'create extension if not exists ' || quote_ident(e.extname) || ' with schema ' || quote_ident(n.nspname) || ';' as definicion
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace where e.extname <> 'plpgsql'
  union all
  -- 2 · Tipos (listas de valores)
  select 2, 'tipo', t.typname::text,
         'create type public.' || quote_ident(t.typname) || ' as enum (' ||
         string_agg(quote_literal(en.enumlabel), ', ' order by en.enumsortorder) || ');'
    from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum en on en.enumtypid = t.oid
   where n.nspname = 'public' group by t.typname
  union all
  -- 3 · Secuencias
  select 3, 'secuencia', s.sequencename::text,
         'create sequence if not exists public.' || quote_ident(s.sequencename) || ' start ' || s.start_value || ';'
    from pg_sequences s where s.schemaname = 'public'
     -- las de columnas "identity" las crea la propia tabla
     and not exists (select 1 from pg_depend dp where dp.objid = ('public.' || quote_ident(s.sequencename))::regclass and dp.deptype = 'i')
  union all
  -- 4 · Tablas (columnas, tipos, valores por defecto)
  select 4, 'tabla', t.relname::text,
         'create table public.' || quote_ident(t.relname) || ' (' || E'\n' ||
         string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
           || case when a.attidentity = 'a' then ' generated always as identity'
                   when a.attidentity = 'd' then ' generated by default as identity' else '' end
           || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
                   when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end
           || case when a.attnotnull then ' not null' else '' end,
           E',\n' order by a.attnum) || E'\n);'
           || coalesce(E'\ncomment on table public.' || quote_ident(t.relname) || ' is ' || quote_literal(obj_description(t.oid, 'pg_class')) || ';', '')
    from tablas t join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum
   group by t.oid, t.relname
  union all
  -- 5 · Restricciones (5 = clave primaria, únicas y validaciones · 6 = relaciones entre tablas)
  select case when k.contype = 'f' then 6 else 5 end, 'restriccion', t.relname || '.' || k.conname,
         'alter table public.' || quote_ident(t.relname) || ' add constraint ' || quote_ident(k.conname) || ' ' || pg_get_constraintdef(k.oid) || ';'
    from pg_constraint k join tablas t on t.oid = k.conrelid
  union all
  -- 7 · Índices (los que no vienen de una restricción)
  select 7, 'indice', i.indexname::text, i.indexdef || ';'
    from pg_indexes i
   where i.schemaname = 'public'
     and not exists (select 1 from pg_constraint k where k.conname = i.indexname and k.connamespace = 'public'::regnamespace)
  union all
  -- 8 · Funciones
  select 8, 'funcion', p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         pg_get_functiondef(p.oid) || ';'
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend dp where dp.objid = p.oid and dp.deptype = 'e')
  union all
  -- 9 · Vistas
  select 9, 'vista', c.relname::text,
         'create or replace view public.' || quote_ident(c.relname)
           || coalesce(' with (' || array_to_string(c.reloptions, ', ') || ')', '')
           || E' as\n' || rtrim(pg_get_viewdef(c.oid, true), ';') || ';'
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind in ('v', 'm')
  union all
  -- 10 · Triggers (de las tablas propias y los que llaman a funciones propias, ej. sobre auth.users)
  select 10, 'trigger', tc.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
    from pg_trigger tg join pg_class tc on tc.oid = tg.tgrelid join pg_namespace tn on tn.oid = tc.relnamespace
    join pg_proc fp on fp.oid = tg.tgfoid join pg_namespace fn on fn.oid = fp.pronamespace
   where not tg.tgisinternal and (tn.nspname = 'public' or fn.nspname = 'public')
  union all
  -- 11 · Seguridad por filas activada
  select 11, 'rls', t.relname::text, 'alter table public.' || quote_ident(t.relname) || ' enable row level security;'
    from tablas t join pg_class c on c.oid = t.oid where c.relrowsecurity
  union all
  -- 12 · Reglas de seguridad (políticas)
  select 12, 'politica', p.schemaname || '.' || p.tablename || ' · ' || p.policyname,
         'create policy ' || quote_ident(p.policyname) || ' on ' || p.schemaname || '.' || quote_ident(p.tablename)
           || ' as ' || lower(p.permissive) || ' for ' || lower(p.cmd) || ' to ' || array_to_string(p.roles, ', ')
           || coalesce(' using (' || p.qual || ')', '') || coalesce(' with check (' || p.with_check || ')', '') || ';'
    from pg_policies p where p.schemaname in ('public', 'storage')
  union all
  -- 13 · Funciones que se pueden usar SIN iniciar sesión (anon)
  select 13, 'permiso', r.routine_name::text,
         'grant execute on function public.' || quote_ident(r.routine_name) || ' to anon;'
    from information_schema.routine_privileges r
   where r.grantee = 'anon' and r.routine_schema = 'public' and r.privilege_type = 'EXECUTE'
  union all
  -- 14 · Carpetas de archivos (Storage)
  select 14, 'bucket', b.id::text,
         'insert into storage.buckets (id, name, public) values (' || quote_literal(b.id) || ', ' || quote_literal(b.name) || ', ' || b.public || ') on conflict do nothing;'
    from storage.buckets b
)
select orden, tipo, nombre, definicion from foto order by orden, nombre;
